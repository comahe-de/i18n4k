package example.jvm

import de.comahe.i18n4k.Locale
import de.comahe.i18n4k.config.I18n4kConfigDefault
import de.comahe.i18n4k.getDisplayNameInLocale
import de.comahe.i18n4k.i18n4k
import de.comahe.i18n4k.messages.provider.MessagesProviderViaResource
import example.greeting
import example.title
import x.y.MyMessages
import javax.swing.BoxLayout
import javax.swing.JButton
import javax.swing.JFrame
import javax.swing.JLabel
import javax.swing.JPanel
import javax.swing.JTextField
import javax.swing.WindowConstants
import javax.swing.event.DocumentEvent
import javax.swing.event.DocumentListener

fun main() {
    val config = I18n4kConfigDefault()
    i18n4k = config

    // Locales that are not inlined into the Kotlin code are loaded from the
    // resource files generated by the i18n4k Kotlin Toolchain plugin.
    MyMessages.registerTranslation(
        MessagesProviderViaResource(pathToResource = "/x/y/MyMessages_fr.i18n4k.txt")
    )
    MyMessages.registerTranslation(
        MessagesProviderViaResource(pathToResource = "/x/y/MyMessages_nl.i18n4k.txt")
    )
    MyMessages.registerTranslation(
        MessagesProviderViaResource(pathToResource = "/x/y/MyMessages_en_US_texas.i18n4k.txt")
    )

    val titleLabel = JLabel()
    val messageLabel = JLabel()
    val nameField = JTextField("Kotlin")
    val buttons = mutableMapOf<Locale, JButton>()

    fun updateUi() {
        titleLabel.text = title()
        messageLabel.text = greeting(nameField.text)
        buttons.forEach { (locale, button) -> button.isSelected = locale == config.locale }
    }

    val buttonPanel = JPanel()
    for (locale in MyMessages.locales) {
        val button = JButton(locale.getDisplayNameInLocale())
        button.addActionListener {
            config.locale = locale
            updateUi()
        }
        buttons[locale] = button
        buttonPanel.add(button)
    }

    nameField.document.addDocumentListener(object : DocumentListener {
        override fun insertUpdate(e: DocumentEvent) = updateUi()
        override fun removeUpdate(e: DocumentEvent) = updateUi()
        override fun changedUpdate(e: DocumentEvent) = updateUi()
    })

    updateUi()

    val content = JPanel()
    content.layout = BoxLayout(content, BoxLayout.Y_AXIS)
    content.add(titleLabel)
    content.add(nameField)
    content.add(messageLabel)
    content.add(buttonPanel)

    JFrame("i18n4k - example-mpp (Kotlin Toolchain)").apply {
        defaultCloseOperation = WindowConstants.EXIT_ON_CLOSE
        add(content)
        setSize(600, 220)
        isVisible = true
    }
}
